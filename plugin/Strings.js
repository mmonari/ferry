// One pass over the template, so an argument that itself contains "%2" (a peer may be named
// "100%2") is never read as a hole of its own.
function format(text, args) {
  var out = String(text);
  if (!args) return out;
  return out.replace(/%(\d+)/g, function (hole, n) {
    var i = Number(n) - 1;
    return i >= 0 && i < args.length ? String(args[i]) : hole;
  });
}

// t("tip.away", [peer, chord]). A missing key answers with the key, never an empty string, so
// a typo is visible on screen instead of blank.
function t(key, args) {
  var text = en[key];
  return text === undefined ? String(key) : format(text, args);
}

// True when the table has the key. The model asks before it builds a key from data (a failure reason
// ferryd sends), so an unknown reason falls back to a general text and not to a key on screen. The settings
// view asks too: it words the keys ferryd adds later from the schema, and tells "no polish yet" from a typo.
function has(key) {
  return en[key] !== undefined;
}
